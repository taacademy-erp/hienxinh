-- ==============================================================================
-- HIỀN XINH BEAUTY CENTER - SUPABASE DATABASE SCHEMA
-- Hệ thống cơ sở dữ liệu hoàn chỉnh cho Web App Quản lý Spa & Thẩm mỹ
-- ==============================================================================

-- 1. BẢNG NGƯỜI DÙNG & TÀI KHOẢN HỆ THỐNG (users)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('chu', 'ql', 'nhanvien')),
    avatar VARCHAR(10) DEFAULT 'U',
    phone VARCHAR(25),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. BẢNG DANH SÁCH NHÂN VIÊN & HOA HỒNG (staff)
CREATE TABLE IF NOT EXISTS public.staff (
    id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    initials VARCHAR(10),
    color VARCHAR(50) DEFAULT 'bg-rose-600',
    role VARCHAR(100) DEFAULT 'Kỹ thuật viên',
    phone VARCHAR(25),
    commission_rate NUMERIC(5,2) DEFAULT 5.0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. BẢNG DANH MỤC DỊCH VỤ & BẢNG GIÁ SPA (services)
CREATE TABLE IF NOT EXISTS public.services (
    id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    price NUMERIC(15,2) NOT NULL DEFAULT 0,
    category VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. BẢNG TÀI KHOẢN NGÂN HÀNG & DÒNG TIỀN (bank_accounts)
CREATE TABLE IF NOT EXISTS public.bank_accounts (
    id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    bank_name VARCHAR(100) NOT NULL,
    account_number VARCHAR(50) NOT NULL,
    account_holder VARCHAR(100) NOT NULL,
    balance NUMERIC(15,2) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. BẢNG KHÁCH HÀNG (customers)
CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(25) NOT NULL,
    birthdate VARCHAR(25),
    customer_group VARCHAR(50) DEFAULT 'Khách mới',
    source VARCHAR(50) DEFAULT 'Tại quầy',
    address TEXT,
    notes TEXT,
    total_spent NUMERIC(15,2) DEFAULT 0,
    visit_count INT DEFAULT 0,
    last_visit VARCHAR(25),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. BẢNG HÓA ĐƠN DỊCH VỤ (invoices)
CREATE TABLE IF NOT EXISTS public.invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) UNIQUE NOT NULL,
    date VARCHAR(25) NOT NULL,
    customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL,
    customer_name VARCHAR(150) NOT NULL,
    customer_phone VARCHAR(25),
    customer_dob VARCHAR(25),
    staff_id VARCHAR(20) REFERENCES public.staff(id) ON DELETE SET NULL,
    staff_name VARCHAR(100),
    services JSONB NOT NULL DEFAULT '[]'::jsonb,
    service_summary TEXT,
    subtotal NUMERIC(15,2) NOT NULL DEFAULT 0,
    discount NUMERIC(15,2) DEFAULT 0,
    total_amount NUMERIC(15,2) NOT NULL DEFAULT 0,
    payment_method VARCHAR(50) NOT NULL DEFAULT 'Chuyển khoản',
    bank_account VARCHAR(100),
    notes TEXT,
    status VARCHAR(50) DEFAULT 'Đã thanh toán',
    created_by VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. BẢNG CHI PHÍ VẬN HÀNH (expenses)
CREATE TABLE IF NOT EXISTS public.expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) UNIQUE NOT NULL,
    date VARCHAR(25) NOT NULL,
    amount NUMERIC(15,2) NOT NULL DEFAULT 0,
    category VARCHAR(50) NOT NULL CHECK (category IN ('Marketing', 'Mặt bằng', 'Mỹ phẩm', 'Nhân sự')),
    content TEXT NOT NULL,
    notes TEXT,
    created_by VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. BẢNG SỔ QUỸ & LỊCH SỬ GIAO DỊCH DÒNG TIỀN (daily_transactions)
CREATE TABLE IF NOT EXISTS public.daily_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date VARCHAR(25) NOT NULL,
    type VARCHAR(20) NOT NULL CHECK (type IN ('income', 'expense')),
    amount NUMERIC(15,2) NOT NULL DEFAULT 0,
    content TEXT NOT NULL,
    reference_code VARCHAR(30),
    account_id VARCHAR(50),
    account_name VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

